#!/usr/bin/env node
// Regenerates js/tables8.js from tests/fixtures/tables8.json (extracted from www.qfit.com/book/tables8.htm).
const fs = require('fs'), path = require('path');
const src = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'tests', 'fixtures', 'tables8.json'), 'utf8'));
const tables = src.tables.map((t) => ({ system: t.system, rules: t.rules.join(' '),
  rows: t.rows.map((r) => [r.score, r.pen, r.spread, r.ev, r.r20_5k.unit, r.r20_5k.win100, r.r2_10k.unit, r.r2_10k.win100, r.r025_100k.unit, r.r025_100k.win100]) }));
const out = `/* Generated by tools/build-tables8.js. Do not edit by hand.
   Source: ${src.source}
   Row: [SCORE, penetration (decks dealt of 8), spread 1:N, EV %, unit $ @20%/$5K, win/100 $ @20%/$5K,
         unit $ @2%/$10K, win/100 $ @2%/$10K, unit $ @0.25%/$100K, win/100 $ @0.25%/$100K] */
(function (root) {
  const BJ = (root.BJ = root.BJ || {});
  BJ.TABLES8 = ${JSON.stringify({ source: src.source, tables })};
})(typeof globalThis !== 'undefined' ? globalThis : this);
`;
fs.writeFileSync(path.join(__dirname, '..', 'js', 'tables8.js'), out);
console.log('wrote js/tables8.js', out.length, 'bytes');
